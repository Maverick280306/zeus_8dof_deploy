#!/usr/bin/env python3
"""
Freeze a trained run into the bundle the Pi loads. Run on the TRAINING machine.

    cd biped_walk_rl/platforms/zeus
    ZEUS_VARIANT=mukesh QUIET_LIMITS=1 python <repo>/zeus_control_interface/scripts/export_policy.py \
        --run m1_mukesh --speed 0.30 --out <repo>/zeus_control_interface/policy/m1_mukesh_3M

Writes
    policy.npz      weights, normaliser, the gait at --speed, deployment constants
    golden.npz      observations and what SB3 itself answered, from real rollouts
    manifest.json   provenance: run, steps, sha256 of every input

and, into --firmware, gait_ref.c/.h for stm32_zeuss.

Only one speed goes out because the board stores one stride. --speed must be a
library row, not a blend: a row is a solved periodic orbit, a blend of two is not.
"""
import argparse
import datetime
import hashlib
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.getcwd())
os.environ.setdefault("QUIET_LIMITS", "1")


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


# gait_ref columns. Right leg only: the firmware plays the left half a stride
# behind and flips the roll joints, which this library satisfies to machine
# precision (asserted below, not assumed).
SLOTS = ["hip_roll", "hip_pitch", "knee_pitch", "ankle_pitch", "ankle_roll"]


def write_c(a, out):
    idx = [a["names"].index("right_" + s) for s in SLOTS]
    n = a["q"].shape[0]
    h = f"""#ifndef GAIT_REF_H
#define GAIT_REF_H

#include <stdint.h>

/*
 * Reference gait for the right leg. GENERATED by zeus_26
 * zeus_control_interface/scripts/export_policy.py from
 *   {a['lib']}
 *   sha256 {a['lib_sha']}
 * row v = {a['speed']:.2f} m/s. DO NOT EDIT - regenerate.
 *
 * This is the stride policy {a['run']} was TRAINED on. Replacing it with
 * any other table invalidates the policy, and rl_policy_node refuses to enable
 * if ref_angle differs from the copy it carries.
 *
 * Rows are OUTPUT-side values, in the URDF sign convention. Scale them to each
 * drive's own turns (the ankle encoder sits on the motor) where the command is
 * sent, not here.
 *
 *   g_gait_turns  turns          position
 *   g_gait_vel    turns/s        velocity at nominal playback
 *   g_gait_tau    Nm             joint torque the optimiser solved for
 */

#define GAIT_COL_HIP_ROLL    0
#define GAIT_COL_HIP_PITCH   1
#define GAIT_COL_KNEE        2
#define GAIT_COL_ANKLE       3
#define GAIT_COL_ANKLE_ROLL  4

#define GAIT_SAMPLES     {n}
#define GAIT_JOINTS      {len(SLOTS)}
#define GAIT_DT_S        {a['T'] / n:.9f}f
#define GAIT_RATE_HZ     {n / a['T']:.4f}f
#define GAIT_CYCLE_S     {a['T']:.9f}f

extern const float g_gait_turns[GAIT_SAMPLES][GAIT_JOINTS];
extern const float g_gait_vel[GAIT_SAMPLES][GAIT_JOINTS];
extern const float g_gait_tau[GAIT_SAMPLES][GAIT_JOINTS];

/* Linear interpolation with wrap-around, exactly as in training. Any output may
   be NULL. Velocity and torque are at nominal playback (APP_GAIT_SPEED 1.0). */
void gait_sample(float phase, float *turns_out);
void gait_sample_all(float phase, float *turns_out, float *vel_out, float *tau_out);

#endif /* GAIT_REF_H */
"""

    def table(name, arr):
        rows = ",\n".join("    { " + ", ".join(f"{v:+.7f}f" for v in r) + " }" for r in arr)
        return f"const float {name}[GAIT_SAMPLES][GAIT_JOINTS] = {{\n{rows}\n}};\n"

    tp = 2.0 * np.pi
    c = f"""#include "gait_ref.h"

/* Generated by zeus_26 export_policy.py from {a['run']}. Do not edit. */
{table('g_gait_turns', a['q'][:, idx] / tp)}
{table('g_gait_vel', a['dq'][:, idx] / tp)}
{table('g_gait_tau', a['tau'][:, idx])}
static void lerp(const float t[GAIT_SAMPLES][GAIT_JOINTS], int i, int j, float f, float *out)
{{
    if (out == 0)
    {{
        return;
    }}
    for (int k = 0; k < GAIT_JOINTS; k++)
    {{
        out[k] = t[i][k] + (t[j][k] - t[i][k]) * f;
    }}
}}

void gait_sample_all(float phase, float *turns_out, float *vel_out, float *tau_out)
{{
    /* Wrap into [0,1). The phase clock is free-running. */
    phase -= (float)(int)phase;
    if (phase < 0.0f)
    {{
        phase += 1.0f;
    }}

    float x = phase * (float)GAIT_SAMPLES;
    int   i = (int)x;
    float f = x - (float)i;

    if (i >= GAIT_SAMPLES)
    {{
        i = GAIT_SAMPLES - 1;
        f = 1.0f;
    }}

    int j = (i + 1) % GAIT_SAMPLES;

    lerp(g_gait_turns, i, j, f, turns_out);
    lerp(g_gait_vel, i, j, f, vel_out);
    lerp(g_gait_tau, i, j, f, tau_out);
}}

void gait_sample(float phase, float *turns_out)
{{
    gait_sample_all(phase, turns_out, 0, 0);
}}
"""
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "gait_ref.h"), "w").write(h)
    open(os.path.join(out, "gait_ref.c"), "w").write(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--speed", type=float, default=0.30)
    ap.add_argument("--out", required=True)
    ap.add_argument("--firmware")
    ap.add_argument("--golden-steps", type=int, default=300)
    a = ap.parse_args()

    import torch
    from stable_baselines3 import PPO
    from stable_baselines3.common.vec_env import DummyVecEnv, VecNormalize
    import zeus_env as ze
    import zeus_model as zm

    run = os.path.join("runs", a.run)
    cfg = json.load(open(os.path.join(run, "config.json")))
    lib_path = cfg["lib"]
    env = ze.ZeusWalkEnv(lib_path, dr=False, seed=7)
    model = PPO.load(os.path.join(run, "final.zip"), device="cpu")
    vn = VecNormalize.load(os.path.join(run, "final_vecnorm.pkl"), DummyVecEnv([lambda: env]))
    vn.training = False

    L = np.load(lib_path, allow_pickle=True)
    row = int(np.argmin(np.abs(L["velocities"] - a.speed)))
    if abs(L["velocities"][row] - a.speed) > 1e-9:
        raise SystemExit(f"{a.speed} is not a library row: {L['velocities']}")
    q, dq, tau = L["q_joints"][row], L["dq_joints"][row], L["tau_joints"][row]
    names = [str(n) for n in L["joint_order"]]
    assert names == list(zm.JOINT_NAMES)

    # The board plays one leg's column twice. If the library were not exactly
    # half-stride symmetric the left leg would get a gait it was never trained on.
    S, half = zm.mirror_matrix(), q.shape[0] // 2
    for arr in (q, dq, tau):
        assert np.abs(np.roll(arr, -half, axis=0) @ S.T - arr).max() < 1e-9

    sd = model.policy.state_dict()
    layers = [("mlp_extractor.policy_net.0", 0), ("mlp_extractor.policy_net.2", 1),
              ("mlp_extractor.policy_net.4", 2), ("action_net", 3)]
    w = {}
    for prefix, i in layers:
        w[f"w{i}"] = sd[prefix + ".weight"].numpy().astype(np.float32)
        w[f"b{i}"] = sd[prefix + ".bias"].numpy().astype(np.float32)

    os.makedirs(a.out, exist_ok=True)
    site = env.m.site_pos[env.m.site("imu").id].copy()
    np.savez_compressed(
        os.path.join(a.out, "policy.npz"), n_layers=len(layers), **w,
        obs_mean=vn.obs_rms.mean, obs_var=vn.obs_rms.var, obs_eps=vn.epsilon,
        clip_obs=vn.clip_obs, joint_names=np.array(names),
        spring_order=np.array(zm.SPRING_ORDER), act_scale=ze.ACT_SCALE, act_fc=ze.ACT_FC,
        policy_hz=1.0 / ze.DT, hist=ze.HIST, frame_size=ze.OBS1, imu_in_base=site,
        tilt_stop=ze.TILT_TERM, z_stop=0.40, gait_speed=a.speed,
        gait_period=float(L["T"][row]), gait_q=q, gait_dq=dq, gait_tau=tau)

    # Real rollouts at the deployed speed, so the golden inputs are the inputs
    # the network will actually see rather than random vectors.
    O, A = [], []
    for phase in (0.0, 0.5):
        env.set_vcmd(a.speed)
        obs, _ = env.reset(seed=3, options={"phase": phase})
        for _ in range(a.golden_steps // 2):
            act, _ = model.predict(vn.normalize_obs(obs[None]), deterministic=True)
            O.append(obs.copy()); A.append(act[0].copy())
            obs, _, term, trunc, _ = env.step(act[0])
            if term or trunc:
                break
    np.savez_compressed(os.path.join(a.out, "golden.npz"), obs=np.array(O), action=np.array(A))

    json.dump({
        "run": a.run, "variant": zm.VARIANT, "policy_file": "final.zip",
        "num_timesteps": int(model.num_timesteps), "deployed_speed_m_s": a.speed,
        "gait_period_s": float(L["T"][row]),
        "network": "MLP 183-256-256-128-10, ELU, deterministic mean",
        "observation": "61 values x 3 frames at 50 Hz, oldest first",
        "sha256": {"final.zip": sha(os.path.join(run, "final.zip")),
                   "final_vecnorm.pkl": sha(os.path.join(run, "final_vecnorm.pkl")),
                   "gait_library.npz": sha(lib_path), "zeus.xml": sha(zm.XML),
                   "mukesh.urdf": sha(zm.URDF)},
        "exported": datetime.date.today().isoformat(),
        "training_config": cfg,
    }, open(os.path.join(a.out, "manifest.json"), "w"), indent=1)

    if a.firmware:
        write_c(dict(names=names, q=q, dq=dq, tau=tau, T=float(L["T"][row]), speed=a.speed,
                     lib=lib_path, lib_sha=sha(lib_path), run=a.run), a.firmware)
    print(f"exported {a.run} at {model.num_timesteps} steps, {a.speed} m/s, "
          f"T={float(L['T'][row]):.4f}s, {len(O)} golden pairs -> {a.out}")


if __name__ == "__main__":
    main()
